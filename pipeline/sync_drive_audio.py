"""
pipeline/sync_drive_audio.py
Synchronizes audio files generated by GitHub Actions in Google Drive to the local data/audio directory.
Ensures offline and local file:/// playback works seamlessly without Google Drive CORP/CORS blocking.
"""

import os
import sys
import json
import requests

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from pipeline.cloud_pipeline_runner import fetch_existing_sheet_database

def sync_audio_from_drive(force=False):
    print("=" * 70)
    print("SYNCHRONIZING GOOGLE DRIVE AUDIO FILES TO LOCAL DISK")
    print("=" * 70)

    db = fetch_existing_sheet_database()
    print(f"Loaded {len(db)} question records from Google Sheets.")

    total_downloaded = 0
    total_already_local = 0

    for q_key, rec in db.items():
        sj = rec.get('summary_json')
        if not sj:
            continue
        try:
            parsed = json.loads(sj)
        except Exception:
            continue

        pts = []
        if parsed.get('root'):
            pts.append(parsed['root'])
        for b in parsed.get('branches', []):
            pts.extend(b.get('points', []))

        for p in pts:
            fid = p.get('drive_audio_id')
            rel_path = p.get('audio_file')
            if not fid or not rel_path or fid.startswith('DRIVE_PT_'):
                continue

            local_path = os.path.join(PROJECT_ROOT, 'data', 'audio', rel_path.replace('/', os.sep))
            if not force and os.path.exists(local_path) and os.path.getsize(local_path) > 1000:
                total_already_local += 1
                continue

            os.makedirs(os.path.dirname(local_path), exist_ok=True)
            url = f"https://drive.google.com/uc?export=download&id={fid}"
            try:
                r = requests.get(url, timeout=20, allow_redirects=True)
                if r.status_code == 200 and len(r.content) > 1000:
                    with open(local_path, 'wb') as f:
                        f.write(r.content)
                    print(f"  ✓ [{q_key[0]} Ch{q_key[1]} Q{q_key[2]}] Downloaded {rel_path} ({len(r.content)} bytes)")
                    total_downloaded += 1
                else:
                    print(f"  ✗ [{q_key[0]} Ch{q_key[1]} Q{q_key[2]}] Failed to download {rel_path}: HTTP {r.status_code}")
            except Exception as e:
                print(f"  ✗ [{q_key[0]} Ch{q_key[1]} Q{q_key[2]}] Download error on {rel_path}: {e}")

    print("=" * 70)
    print(f"Audio sync complete! New files downloaded: {total_downloaded} | Already on disk: {total_already_local}")
    print("=" * 70)

if __name__ == '__main__':
    force_sync = '--force' in sys.argv
    sync_audio_from_drive(force=force_sync)
